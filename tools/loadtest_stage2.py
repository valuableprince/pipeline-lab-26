#!/usr/bin/env python3
"""LOADTEST-03: bounded, owner-approved SA-MP headless-client scenario runner.

Requires a separately obtained compatible RakClient binary. This tool does not
implement RakNet or pretend that TCP/UDP probes are authenticated players.
"""
from __future__ import annotations

import argparse
import csv
from datetime import datetime
import ipaddress
import json
import os
from pathlib import Path
import re
import signal
import subprocess
import sys
import tempfile
import time

MAX_CLIENTS = 50
MAX_SECONDS = 600
MAX_RATE = 2.0
ALLOWED_SCENARIOS = ("idle", "commands")
NICK_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]{2,14}$")
FIELDS = (
    "seconds", "started", "transport_connected", "game_joined", "authenticated",
    "spawned", "exited", "failed", "alive",
)

# Tarkenso dialogs as defined in gamemodes/signal0317.pwn.
INTRO, REGISTER, CONFIRM, BACKGROUND, LOGIN, SUCCESS, REGION = (
    6100, 6101, 6102, 6103, 6104, 6105, 6106
)

SCRIPT_TEMPLATE = r'''--!nonstrict
-- Per-client script generated by TARKENSO stage 2. Removed after the run.
local events = require("samp.events")
local secret = __SECRET__
local mode = __MODE__
local scenario = __SCENARIO__
local running = true
local spawned = false
local registerSeen = false
local loginSeen = false

function events.onShowDialog(dialogId, style, title, button1, button2, body)
    if dialogId == 6100 then
        sampSendDialogResponse(dialogId, 1, 0, "")
        return false
    elseif dialogId == 6101 then
        if registerSeen then
            print("LT_FATAL:registration_repeated")
            return false
        end
        registerSeen = true
        if mode ~= "register" then
            print("LT_FATAL:account_missing")
            return false
        end
        sampSendDialogResponse(dialogId, 1, 0, secret)
        return false
    elseif dialogId == 6102 then
        sampSendDialogResponse(dialogId, 1, 0, secret)
        return false
    elseif dialogId == 6103 or dialogId == 6106 then
        sampSendDialogResponse(dialogId, 1, 0, "")
        return false
    elseif dialogId == 6104 then
        if loginSeen then
            print("LT_FATAL:login_repeated")
            return false
        end
        loginSeen = true
        sampSendDialogResponse(dialogId, 1, 0, secret)
        return false
    elseif dialogId == 6105 then
        print("LT_STATE:authenticated")
        sampSendDialogResponse(dialogId, 1, 0, "")
        return false
    end
end

-- Client->server RPC 50 is SERVERCOMMAND: uint32 little endian length + bytes.
local function command(text)
    if #text > 127 then return end
    sampSendRpc(50, string.char(#text, 0, 0, 0) .. text)
end

registerHandler("onSpawn", function()
    if spawned then return end
    spawned = true
    print("LT_STATE:spawned")
    if scenario == "commands" then
        newTask(function()
            while running do
                wait(30000)  -- not a flood: 1 harmless query every 30 seconds
                if running then command("/cleanstats") end
            end
        end)
    end
end)

registerHandler("onDisconnect", function()
    running = false
    print("LT_STATE:disconnected")
end)
'''

def parse_target(value: str) -> tuple[str, int]:
    """SA-MP host:port target with no scheme, path, userinfo or IPv6 ambiguity."""
    if any(ch in value for ch in ("/", "@", " ", "\\", "\n", "\r")):
        raise ValueError("server must be an exact host:port address")
    if value.count(":") != 1:
        raise ValueError("server must be host:port (IPv4/DNS)")
    host, port_raw = value.rsplit(":", 1)
    if not host or not re.fullmatch(r"[A-Za-z0-9.-]{1,253}", host):
        raise ValueError("invalid server hostname")
    if not port_raw.isascii() or not port_raw.isdecimal():
        raise ValueError("invalid server port")
    port = int(port_raw)
    if not 1 <= port <= 65535:
        raise ValueError("server port out of range")
    return host, port


def is_local_target(host: str) -> bool:
    if host.lower() == "localhost":
        return True
    try:
        return ipaddress.ip_address(host).is_loopback
    except ValueError:
        return False


def validate(args: argparse.Namespace) -> tuple[str, int]:
    host, port = parse_target(args.server)
    if args.confirm_target != args.server:
        raise ValueError("--confirm-target must match --server exactly")
    if not is_local_target(host) and not args.remote_approved:
        raise ValueError("remote target requires explicit --remote-approved")
    if not 1 <= args.count <= MAX_CLIENTS:
        raise ValueError(f"client count must be 1..{MAX_CLIENTS}")
    if not 10 <= args.seconds <= MAX_SECONDS:
        raise ValueError(f"test length must be 10..{MAX_SECONDS} seconds")
    if not 0 < args.rate <= MAX_RATE:
        raise ValueError(f"launch rate must be >0 and <= {MAX_RATE}/second")
    if not NICK_RE.fullmatch(args.prefix) or len(args.prefix) > 11:
        raise ValueError("nickname prefix must start with a letter and be 3..11 ASCII characters")
    if args.scenario not in ALLOWED_SCENARIOS:
        raise ValueError("invalid scenario")
    if args.mode not in ("login", "register"):
        raise ValueError("invalid authentication mode")
    if not args.dry_run:
        if not args.client_bin.is_file():
            raise ValueError("headless client binary not found")
        if not os.access(args.client_bin, os.X_OK):
            raise ValueError("headless client binary is not executable")
        password = os.environ.get("TARKENSO_LOAD_PASSWORD", "")
        if not 8 <= len(password) <= 64 or any(ord(c) < 33 or ord(c) > 126 for c in password):
            raise ValueError("set TARKENSO_LOAD_PASSWORD to 8..64 printable ASCII characters")
    return host, port


def render_script(password: str, mode: str, scenario: str) -> str:
    if not 8 <= len(password) <= 64 or any(ord(c) < 33 or ord(c) > 126 for c in password):
        raise ValueError("invalid test password")
    return (SCRIPT_TEMPLATE.replace("__SECRET__", json.dumps(password))
            .replace("__MODE__", json.dumps(mode))
            .replace("__SCENARIO__", json.dumps(scenario)))


def unique_report_dir(root: Path, now: datetime) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    for rev in range(1, 1000):
        path = root / f"load_net_{rev:02d}_{now:%d.%m.%Y}"
        try:
            path.mkdir(mode=0o700)
            return path
        except FileExistsError:
            continue
    raise RuntimeError("daily report revision limit (999) reached")


def classify_log(text: str) -> dict[str, bool]:
    """States are confirmed ONLY from the actual client transcript."""
    return {
        "transport_connected": "raknet transport connected" in text,
        "game_joined": "joined game" in text,
        "authenticated": "LT_STATE:authenticated" in text,
        "spawned": "LT_STATE:spawned" in text,
        "failed": "LT_FATAL:" in text,
    }


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--server", required=True, help="owned open.mp host:port")
    parser.add_argument("--confirm-target", required=True, help="repeat exact host:port as ownership acknowledgement")
    parser.add_argument("--remote-approved", action="store_true", help="explicit approval for non-loopback target")
    parser.add_argument("--client-bin", type=Path, default=Path("rakclient"), help="path to compatible RakClient executable")
    parser.add_argument("--count", type=int, default=5)
    parser.add_argument("--seconds", type=int, default=90)
    parser.add_argument("--rate", type=float, default=0.5, help="client starts per second (maximum 2)")
    parser.add_argument("--mode", choices=("login", "register"), default="login")
    parser.add_argument("--scenario", choices=ALLOWED_SCENARIOS, default="idle")
    parser.add_argument("--prefix", default="LT_Bot")
    parser.add_argument("--output", type=Path, default=Path("loadtest_results"))
    parser.add_argument("--dry-run", action="store_true", help="validate and show configuration only: NO connections")
    return parser.parse_args(argv)


def snapshot(bots: list[dict], elapsed: int) -> dict:
    result = dict.fromkeys(FIELDS, 0)
    result["seconds"] = elapsed
    result["started"] = len(bots)
    for bot in bots:
        try:
            text = bot["log"].read_text(encoding="utf-8", errors="replace")[-400_000:]
        except OSError:
            text = ""
        status = classify_log(text)
        for key, present in status.items():
            result[key] += int(present)
        rc = bot["process"].poll()
        result["exited"] += int(rc is not None)
        result["alive"] += int(rc is None)
        if rc is not None and rc != 0:
            result["failed"] += int(not status["failed"])
    return result


def stop_processes(bots: list[dict]) -> None:
    for bot in bots:
        proc = bot["process"]
        if proc.poll() is None:
            proc.terminate()
    for bot in bots:
        proc = bot["process"]
        try:
            proc.wait(timeout=3)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait(timeout=3)


def run(args: argparse.Namespace) -> int:
    validate(args)
    if args.dry_run:
        print(json.dumps({
            "server": args.server, "count": args.count, "seconds": args.seconds,
            "rate": args.rate, "mode": args.mode, "scenario": args.scenario,
            "connections_sent": 0
        }, indent=2))
        return 0

    password = os.environ["TARKENSO_LOAD_PASSWORD"]
    target = unique_report_dir(args.output, datetime.now())
    meta = {
        "server": args.server, "planned_clients": args.count,
        "seconds": args.seconds, "rate_per_second": args.rate,
        "mode": args.mode, "scenario": args.scenario,
        "external_client": str(args.client_bin.resolve()),
        "client_protocol_verified": False,
        "start_time": datetime.now().isoformat(timespec="seconds")
    }
    (target / "manifest.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    csv_path = target / "samples.csv"
    bots = []
    start = time.monotonic()
    next_launch = start
    end = start + args.seconds
    last_sample = -5
    interrupted = False
    try:
        with tempfile.TemporaryDirectory(prefix="tarkenso_load_stage2_") as tmp, csv_path.open("w", encoding="utf-8", newline="") as stream:
            writer = csv.DictWriter(stream, fieldnames=FIELDS)
            writer.writeheader()
            while time.monotonic() < end:
                now = time.monotonic()
                if len(bots) < args.count and now >= next_launch:
                    i = len(bots)
                    nick = f"{args.prefix}{i+1:03d}"
                    sandbox = Path(tmp) / nick
                    scripts = sandbox / "scripts"
                    scripts.mkdir(parents=True)
                    script = scripts / "tarkenso.luau"
                    script.write_text(render_script(password, args.mode, args.scenario), encoding="utf-8")
                    try:
                        script.chmod(0o600)
                    except OSError:
                        pass
                    # Avoid RakClient's optional proxy.txt autodiscovery.
                    (sandbox / "proxy.txt").write_text("", encoding="utf-8")
                    log = target / f"{nick}.log"
                    env = dict(os.environ)
                    env.pop("TARKENSO_LOAD_PASSWORD", None)
                    env.pop("RAKCLIENT_LOG", None)  # Works across upstream versions.
                    env["RUST_LOG"] = "info"
                    command = [
                        str(args.client_bin.resolve()), "--server", args.server,
                        "--nick", nick, "--scripts-dir", str(scripts.resolve())
                    ]
                    # Capture stdout for upstream 0.2.0, which lacks RAKCLIENT_LOG.
                    with log.open("wb") as transcript:
                        proc = subprocess.Popen(
                            command, cwd=sandbox, env=env,
                            stdin=subprocess.DEVNULL, stdout=transcript,
                            stderr=subprocess.STDOUT)
                    bots.append({"nick": nick, "process": proc, "log": log})
                    print(f"[stage2] launched {len(bots)}/{args.count}: {nick}")
                    next_launch = now + 1.0 / args.rate
                elapsed = int(now - start)
                if elapsed - last_sample >= 5:
                    values = snapshot(bots, elapsed)
                    writer.writerow(values)
                    stream.flush()
                    last_sample = elapsed
                    print(f"[stage2] {elapsed}s: joined={values['game_joined']} "
                          f"auth={values['authenticated']} spawned={values['spawned']} "
                          f"failed={values['failed']} alive={values['alive']}")
                    # Stop on obvious authentication failure, rather than retrying.
                    if values["failed"] > 0:
                        print("[stage2] abort: one or more clients reported a fatal failure")
                        break
                    if bots and elapsed >= 30 and values["game_joined"] == 0:
                        print("[stage2] abort: no confirmed game joins after 30 seconds")
                        break
                time.sleep(0.2)
    except KeyboardInterrupt:
        interrupted = True
        print("[stage2] interrupted by operator")
    finally:
        stop_processes(bots)
        last = snapshot(bots, int(time.monotonic() - start))
        # At this point processes have been terminated; derive final counts from recorded events.
        meta.update({
            "finish_time": datetime.now().isoformat(timespec="seconds"),
            "launched_clients": len(bots),
            "joined_clients": last["game_joined"],
            "authenticated_clients": last["authenticated"],
            "spawned_clients": last["spawned"],
            "failed_clients": last["failed"],
            "interrupted": interrupted,
        })
        (target / "manifest.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
        print(f"[stage2] report: {target / 'manifest.json'}")
    return 0 if not interrupted and len(bots) == args.count and last["spawned"] == args.count else 1


def main(argv: list[str] | None = None) -> int:
    try:
        return run(parse_args(argv))
    except (ValueError, OSError, RuntimeError) as exc:
        print(f"stage2: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
